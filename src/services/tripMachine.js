// Trip state machine. Every transition is validated here.
const STATES = {
  MATCHING: ['ACCEPTED', 'CANCELLED_BY_CLIENT', 'NO_DRIVER_FOUND'],
  ACCEPTED: ['DRIVER_EN_ROUTE', 'CANCELLED_BY_CLIENT', 'CANCELLED_BY_DRIVER'],
  DRIVER_EN_ROUTE: ['ARRIVED', 'CANCELLED_BY_CLIENT', 'CANCELLED_BY_DRIVER'],
  ARRIVED: ['IN_PROGRESS', 'CANCELLED_BY_CLIENT', 'CANCELLED_BY_DRIVER'],
  IN_PROGRESS: ['COMPLETED', 'DISPUTED'],
  COMPLETED: ['PAID', 'PAYMENT_FAILED', 'DISPUTED'],
  PAYMENT_FAILED: ['PAID', 'DISPUTED'],
  DISPUTED: ['PAID', 'REFUNDED'],
  PAID: ['DISPUTED'],
  CANCELLED_BY_CLIENT: [],
  CANCELLED_BY_DRIVER: [],
  NO_DRIVER_FOUND: [],
  REFUNDED: [],
};

const ACTIVE_STATES = ['MATCHING', 'ACCEPTED', 'DRIVER_EN_ROUTE', 'ARRIVED', 'IN_PROGRESS'];
const DRIVER_BUSY_STATES = ['ACCEPTED', 'DRIVER_EN_ROUTE', 'ARRIVED', 'IN_PROGRESS'];

const canTransition = (from, to) => (STATES[from] || []).includes(to);

module.exports = { STATES, ACTIVE_STATES, DRIVER_BUSY_STATES, canTransition };
